import { createHash } from "node:crypto";
import { inflateRawSync } from "node:zlib";
import { mkdir, readFile } from "node:fs/promises";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";
import { assertBundleFingerprint, computeBuildFingerprint } from "./build-fingerprint.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = "universal";

/**
 * Build the frontend-only DBX package with DBX's official CLI. This wrapper
 * pins Plan Detective to a universal artifact and gives tests a stable entry
 * point; archive construction and manifest/package validation remain owned by
 * dbx-plugin.
 *
 * @param {{ root?: string, outputDirectory?: string, target?: string }} [options]
 * @returns {Promise<{packagePath: string, metadataPath: string, files: string[]}>}
 */
export async function buildPluginPackage(options = {}) {
  const root = path.resolve(options.root ?? ROOT);
  const outputDirectory = path.resolve(options.outputDirectory ?? path.join(root, "dist"));
  const target = options.target ?? process.env.DBX_PLUGIN_TARGET ?? TARGET;
  if (target !== TARGET) {
    throw new Error(`Plan Detective is frontend-only and must be packaged as "${TARGET}" (received "${target}").`);
  }

  const manifest = JSON.parse(await readFile(path.join(root, "manifest.json"), "utf8"));
  if (manifest.entrypoints?.backend !== undefined) {
    throw new Error("Frontend-only packages must not declare manifest.entrypoints.backend.");
  }
  if (!manifest.entrypoints?.ui || manifest.entrypoints.ui.entry !== "ui/index.html") {
    throw new Error("manifest.json must keep the ui/index.html frontend entrypoint.");
  }

  const cli = path.join(root, "node_modules", "@dbx-app", "plugin-cli", "bin", "dbx-plugin.js");
  await mkdir(outputDirectory, { recursive: true });
  const result = spawnSync(process.execPath, [cli, "package", root, "--target", target, "--output-dir", outputDirectory], {
    cwd: root,
    encoding: "utf8",
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`Official dbx-plugin package failed (${result.status}):\n${result.stdout}\n${result.stderr}`);
  }
  process.stdout.write(result.stdout ?? "");
  process.stderr.write(result.stderr ?? "");

  const packageName = `${manifest.id}-${manifest.version}-${target}.dbxp`;
  const packagePath = path.join(outputDirectory, packageName);
  const metadataPath = packagePath.replace(/\.dbxp$/, ".artifact.json");
  const archive = await readFile(packagePath);
  const metadata = JSON.parse(await readFile(metadataPath, "utf8"));
  const entries = inspectPluginZip(archive);
  const bundleText = [...entries]
    .filter(([name]) => name.startsWith("ui/assets/") && name.endsWith(".js"))
    .map(([, entry]) => entry.data.toString("utf8"))
    .join("\n");
  const buildFingerprint = computeBuildFingerprint(root);
  assertBundleFingerprint(bundleText, buildFingerprint);
  const packagedManifest = JSON.parse(entries.get("manifest.json")?.data.toString("utf8") ?? "null");
  if (packagedManifest?.id !== manifest.id || packagedManifest?.version !== manifest.version) {
    throw new Error("Packaged manifest identity/version does not match manifest.json.");
  }
  if (packagedManifest?.entrypoints?.backend !== undefined) {
    throw new Error("Official CLI package unexpectedly contains a backend entrypoint.");
  }
  if (metadata.target !== TARGET || metadata.size !== archive.length || metadata.sha256 !== sha256(archive)) {
    throw new Error("Official CLI artifact metadata does not match the generated .dbxp package.");
  }

  return { packagePath, metadataPath, files: [...entries.keys()].sort(), buildFingerprint };
}

/** Read ZIP entries generated by the official CLI, including stored/deflated files. */
export function inspectPluginZip(buffer) {
  const entries = new Map();
  const minimumEndOffset = Math.max(0, buffer.length - 65_557);
  let endOffset = -1;
  for (let offset = buffer.length - 22; offset >= minimumEndOffset; offset -= 1) {
    if (buffer.readUInt32LE(offset) === 0x06054b50) {
      endOffset = offset;
      break;
    }
  }
  if (endOffset < 0) throw new Error("Invalid .dbxp ZIP: missing end-of-central-directory record.");

  const expectedEntries = buffer.readUInt16LE(endOffset + 10);
  let offset = buffer.readUInt32LE(endOffset + 16);
  while (entries.size < expectedEntries) {
    if (offset + 46 > buffer.length || buffer.readUInt32LE(offset) !== 0x02014b50) {
      throw new Error("Invalid .dbxp ZIP: malformed central directory.");
    }
    const compression = buffer.readUInt16LE(offset + 10);
    const compressedSize = buffer.readUInt32LE(offset + 20);
    const uncompressedSize = buffer.readUInt32LE(offset + 24);
    const filenameLength = buffer.readUInt16LE(offset + 28);
    const extraLength = buffer.readUInt16LE(offset + 30);
    const commentLength = buffer.readUInt16LE(offset + 32);
    const mode = buffer.readUInt32LE(offset + 38) >>> 16;
    const localOffset = buffer.readUInt32LE(offset + 42);
    const nameStart = offset + 46;
    const name = buffer.toString("utf8", nameStart, nameStart + filenameLength);
    if (buffer.readUInt32LE(localOffset) !== 0x04034b50) throw new Error(`Invalid .dbxp ZIP local header: ${name}`);
    const localNameLength = buffer.readUInt16LE(localOffset + 26);
    const localExtraLength = buffer.readUInt16LE(localOffset + 28);
    const dataStart = localOffset + 30 + localNameLength + localExtraLength;
    const compressed = buffer.subarray(dataStart, dataStart + compressedSize);
    let data;
    if (compression === 0) data = Buffer.from(compressed);
    else if (compression === 8) data = inflateRawSync(compressed);
    else throw new Error(`Unsupported .dbxp ZIP compression method ${compression} for ${name}.`);
    if (data.length !== uncompressedSize) throw new Error(`Invalid .dbxp ZIP entry size for ${name}.`);
    entries.set(name, { mode, data });
    offset = nameStart + filenameLength + extraLength + commentLength;
  }
  return entries;
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const result = await buildPluginPackage();
  console.log(`Built frontend-only candidate ${result.packagePath}`);
  console.log(`Build fingerprint ${result.buildFingerprint}`);
  console.log(`Metadata ${result.metadataPath}`);
}
