/**
 * Vite plugin that exposes the committed PostgreSQL fixtures to the UI as a
 * virtual module.
 *
 * Why a virtual module instead of importing `fixtures/**` directly:
 * - it keeps `fixtures/postgres/**` as the single source of truth (loaded
 *   through `tests/helpers/fixtures.js`, the same loader used by `npm test`),
 *   so nothing is copied into hand-written constants;
 * - it bundles only `.plan.json` + display-relevant `.meta.json` fields — never
 *   golden files, `setup.sql`, absolute paths or other test material;
 * - it fails the build when a fixture violates the fixture convention, so the
 *   demo UI cannot silently drift from the tested fixtures.
 *
 * The module is intentionally labeled as offline / demo data; it is not, and
 * must not become, a data source for real plan analysis.
 */

import { buildFixtureCatalog } from "../src/lib/fixture-catalog.js";
import { loadAllFixtures } from "../tests/helpers/fixtures.js";

export const FIXTURE_MODULE_ID = "virtual:plan-detective-fixtures";
const RESOLVED_ID = `\0${FIXTURE_MODULE_ID}`;

export function planDetectiveFixtures() {
  return {
    name: "plan-detective-fixtures",

    /** @param {string} id */
    resolveId(id) {
      return id === FIXTURE_MODULE_ID ? RESOLVED_ID : null;
    },

    /** @param {string} id */
    async load(id) {
      if (id !== RESOLVED_ID) return null;

      const loaded = await loadAllFixtures();
      const catalog = buildFixtureCatalog(loaded);
      const syntheticCount = catalog.filter((entry) => entry.isSynthetic).length;
      this.info(
        `embedded ${catalog.length} offline fixture(s) for fixture-driven mode ` +
          `(${syntheticCount} synthetic); no database or host API is contacted`,
      );

      return [
        "// Generated by scripts/vite-plugin-fixtures.mjs at build time.",
        "// Source of truth: fixtures/postgres/**, read via tests/helpers/fixtures.js.",
        "// Offline / demo data only: no database access, no DBX Host API calls.",
        'export const FIXTURE_SOURCE = "offline-demo";',
        `export const FIXTURE_CATALOG = ${JSON.stringify(catalog)};`,
      ].join("\n");
    },
  };
}
